"""Turn triage results into a Jira comment and a Confluence page (storage format = XHTML)."""

from collections import Counter
from datetime import date
from html import escape

from .classifier import Suggestion
from .jira_client import Issue


def comment_text(s: Suggestion) -> str:
    review = "Needs human review." if s.needs_human else "Please confirm or correct."
    return (
        "[triage-bot] Suggestion only - no fields were changed.\n"
        f"Category: {s.category} (confidence {s.confidence:.0%}, via {s.source})\n"
        f"Summary: {s.summary}\n"
        f"{review}"
    )


def page_title(project: str, day: date | None = None) -> str:
    return f"{project} ticket triage - {(day or date.today()).isoformat()}"


def page_html(results: list[tuple[Issue, Suggestion]], jira_base_url: str = "") -> str:
    counts = Counter(s.category for _, s in results)
    review = sum(s.needs_human for _, s in results)

    rows = []
    for issue, s in results:
        key = escape(issue.key)
        link = f'<a href="{escape(jira_base_url)}/browse/{key}">{key}</a>' if jira_base_url else key
        rows.append(
            "<tr>"
            f"<td>{link}</td><td>{escape(issue.summary)}</td><td>{escape(s.category)}</td>"
            f"<td>{s.confidence:.0%}</td><td>{'Yes' if s.needs_human else 'No'}</td>"
            f"<td>{escape(s.summary)}</td>"
            "</tr>"
        )

    breakdown = "".join(f"<li>{escape(cat)}: {n}</li>" for cat, n in counts.most_common())
    return (
        f"<p><strong>{len(results)}</strong> open ticket(s) triaged, "
        f"<strong>{review}</strong> flagged for human review.</p>"
        f"<h2>By category</h2><ul>{breakdown}</ul>"
        "<h2>Tickets</h2>"
        "<table><tbody>"
        "<tr><th>Key</th><th>Title</th><th>Category</th><th>Confidence</th>"
        "<th>Needs review</th><th>Suggested summary</th></tr>"
        + "".join(rows)
        + "</tbody></table>"
        "<p><em>Generated by triage-bot. Suggestions only; agents make the final call.</em></p>"
    )
